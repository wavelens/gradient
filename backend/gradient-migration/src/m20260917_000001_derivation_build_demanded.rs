//! Defaulting to true is keeping every pending shared build promotable across the deploy. The
//! consistency sweep's absolute recompute is the backfill.

use sea_orm_migration::prelude::*;
use sea_orm_migration::sea_orm::ConnectionTrait;

const UP: &[&str] = &[
    "ALTER TABLE derivation_build ADD COLUMN IF NOT EXISTS demanded boolean NOT NULL DEFAULT true",
];

const DOWN: &[&str] = &["ALTER TABLE derivation_build DROP COLUMN IF EXISTS demanded"];

#[derive(DeriveMigrationName)]
pub struct Migration;

#[async_trait::async_trait]
impl MigrationTrait for Migration {
    async fn up(&self, manager: &SchemaManager) -> Result<(), DbErr> {
        for stmt in UP {
            manager.get_connection().execute_unprepared(stmt).await?;
        }

        Ok(())
    }

    async fn down(&self, manager: &SchemaManager) -> Result<(), DbErr> {
        for stmt in DOWN {
            manager.get_connection().execute_unprepared(stmt).await?;
        }

        Ok(())
    }
}
